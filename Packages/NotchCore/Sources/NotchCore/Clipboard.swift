import CryptoKit
import Foundation

public struct Clip: Codable, Identifiable, Hashable, Sendable {
    public enum Kind: String, Codable, Sendable {
        case text
        case link
        case image
        case files
    }

    public let id: UUID
    public var kind: Kind
    /// For `.text` and `.link`.
    public var text: String?
    /// For `.image`: a file name inside the clipboard images folder.
    public var imageFilename: String?
    /// For `.files`.
    public var filePaths: [String]?
    public var sourceBundleID: String?
    public var sourceAppName: String?
    public var copiedAt: Date
    /// Identical content has the same hash, so copying it again moves the
    /// existing clip to the top instead of adding a duplicate.
    public var contentHash: String

    public init(
        id: UUID = UUID(),
        kind: Kind,
        text: String? = nil,
        imageFilename: String? = nil,
        filePaths: [String]? = nil,
        sourceBundleID: String? = nil,
        sourceAppName: String? = nil,
        copiedAt: Date,
        contentHash: String
    ) {
        self.id = id
        self.kind = kind
        self.text = text
        self.imageFilename = imageFilename
        self.filePaths = filePaths
        self.sourceBundleID = sourceBundleID
        self.sourceAppName = sourceAppName
        self.copiedAt = copiedAt
        self.contentHash = contentHash
    }
}

/// The history list, newest first, capped at `limit`.
public struct ClipboardHistory: Equatable, Sendable {
    public static let limitOptions = [50, 100, 200, 500]
    public static let defaultLimit = 200

    public private(set) var clips: [Clip]
    public private(set) var limit: Int

    public init(clips: [Clip] = [], limit: Int = ClipboardHistory.defaultLimit) {
        self.limit = max(1, limit)
        self.clips = Array(clips.prefix(self.limit))
    }

    public func clip(withHash hash: String) -> Clip? {
        clips.first { $0.contentHash == hash }
    }

    /// Adds `clip` at the top. If the same content is already in the history,
    /// that entry moves to the top instead (keeping its id and files) and
    /// takes the new time and source. Returns clips that fell off the end, so
    /// their files can be deleted.
    @discardableResult
    public mutating func insert(_ clip: Clip) -> [Clip] {
        if let index = clips.firstIndex(where: { $0.contentHash == clip.contentHash }) {
            var existing = clips.remove(at: index)
            existing.copiedAt = clip.copiedAt
            existing.sourceBundleID = clip.sourceBundleID
            existing.sourceAppName = clip.sourceAppName
            clips.insert(existing, at: 0)
            return []
        }
        clips.insert(clip, at: 0)
        return trim()
    }

    @discardableResult
    public mutating func remove(id: UUID) -> Clip? {
        guard let index = clips.firstIndex(where: { $0.id == id }) else { return nil }
        return clips.remove(at: index)
    }

    @discardableResult
    public mutating func removeAll() -> [Clip] {
        defer { clips.removeAll() }
        return clips
    }

    @discardableResult
    public mutating func setLimit(_ newLimit: Int) -> [Clip] {
        limit = max(1, newLimit)
        return trim()
    }

    private mutating func trim() -> [Clip] {
        guard clips.count > limit else { return [] }
        let evicted = Array(clips[limit...])
        clips.removeSubrange(limit...)
        return evicted
    }
}

/// Decides what never gets recorded.
public enum PasteboardFilter {
    /// Markers from the nspasteboard.org convention that password managers
    /// and other apps put on clips that must not be kept.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Apps ignored out of the box. Users can change the list in Settings.
    public static let defaultIgnoredApps: [String] = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    static let imageTypes: Set<String> = ["public.png", "public.tiff"]
    static let textTypes: Set<String> = ["public.utf8-plain-text", "NSStringPboardType"]

    /// Whether a copy is "an image" rather than "some text". Apps list
    /// pasteboard types in their order of preference, so an image wins only
    /// if it comes before any plain text. That keeps a copied spreadsheet
    /// cell (text first, picture second) as text, and a copied picture
    /// (image first, maybe a URL after) as an image.
    public static func prefersImage(types: [String]) -> Bool {
        guard let image = types.firstIndex(where: imageTypes.contains) else { return false }
        guard let text = types.firstIndex(where: textTypes.contains) else { return true }
        return image < text
    }

    public static func shouldRecord(types: [String], sourceBundleID: String?, ignoredApps: Set<String>) -> Bool {
        if types.isEmpty { return false }
        if types.contains(where: privateTypes.contains) { return false }
        if let sourceBundleID, ignoredApps.contains(sourceBundleID) { return false }
        return true
    }
}

public enum ClipText {
    /// A single http(s) URL with nothing else around it.
    public static func isLink(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.rangeOfCharacter(from: .whitespacesAndNewlines) == nil,
              let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              url.host?.isEmpty == false
        else { return false }
        return true
    }

    /// One line for the list: whitespace runs collapsed, cut at `maxLength`.
    public static func preview(_ text: String, maxLength: Int = 200) -> String {
        let collapsed = text
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        guard collapsed.count > maxLength else { return collapsed }
        return String(collapsed.prefix(maxLength)) + "…"
    }

    public static func isBlank(_ text: String) -> Bool {
        text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}

public enum ContentHash {
    public static func of(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    public static func of(text: String) -> String {
        of(Data(("text:" + text).utf8))
    }

    public static func of(filePaths: [String]) -> String {
        of(Data(("files:" + filePaths.joined(separator: "\n")).utf8))
    }
}

/// The history index and image files on disk.
public actor ClipboardStorage {
    public nonisolated let rootURL: URL

    public init(rootURL: URL) {
        self.rootURL = rootURL
    }

    private var indexURL: URL { rootURL.appendingPathComponent("clips.json") }
    private nonisolated var imagesURL: URL { rootURL.appendingPathComponent("Images", isDirectory: true) }

    public func load() -> [Clip] {
        JSONFileStore.load([Clip].self, from: indexURL) ?? []
    }

    public func save(_ clips: [Clip]) throws {
        try JSONFileStore.save(clips, to: indexURL)
    }

    /// Writes PNG data and returns the file name to store on the clip.
    public func writeImage(_ data: Data, id: UUID) throws -> String {
        try FileManager.default.createDirectory(at: imagesURL, withIntermediateDirectories: true)
        let filename = "\(id.uuidString).png"
        let url = imagesURL.appendingPathComponent(filename)
        try data.write(to: url, options: [.atomic])
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        return filename
    }

    public nonisolated func imageURL(_ filename: String) -> URL {
        imagesURL.appendingPathComponent(filename)
    }

    public func deleteFiles(for clips: [Clip]) {
        for filename in clips.compactMap(\.imageFilename) {
            try? FileManager.default.removeItem(at: imageURL(filename))
        }
    }
}
